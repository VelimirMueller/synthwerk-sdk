import { describe, expect, it } from 'vitest'
import brandGroups from '../../../packages/tokens/src/brand-groups.json' with { type: 'json' }
import {
  groupSelector,
  renderTokensCss,
  renderTokensJson,
  resolveColors
} from '../../../packages/tokens/src/css.ts'
import {
  brand,
  contrastAccents,
  defaultGroup,
  deprecatedGroupAliases,
  groupNames,
  groups,
  modes,
  plainGroupStyle,
  primitiveForHex,
  primitives,
  resolveGroupName,
  themeNames
} from '../../../packages/tokens/src/tokens.ts'

const css = renderTokensCss()

/** The declarations of the first top-level rule with exactly this selector. */
function decls(selector: string): Map<string, string> {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '')
  const start = text.indexOf(`\n${selector} {\n`)
  if (start < 0) throw new Error(`No rule "${selector}"`)
  const body = text.slice(text.indexOf('{', start) + 1, text.indexOf('}', start))
  return new Map(
    body
      .split(';')
      .map((d) => d.trim())
      .filter(Boolean)
      .map((d) => [d.slice(0, d.indexOf(':')).trim(), d.slice(d.indexOf(':') + 1).trim()])
  )
}

describe('brand-groups.json (generated by vm-brand scripts/group-tokens.py)', () => {
  it('header - names the generator - says do not edit', () => {
    expect(brandGroups.$comment).toMatch(/vm-brand scripts\/group-tokens\.py/)
    expect(brandGroups.$comment).toMatch(/Do not edit/)
  })

  it('groups - names and order - equal groupNames', () => {
    expect(Object.keys(brandGroups.groups)).toEqual([...groupNames])
  })

  it.each(groupNames)('group %s - default theme - uses the brand.json hex values', (group) => {
    const raw = brandGroups.groups[group]
    const g = groups[group]
    expect(primitives[g.fill]).toBe(raw.fill.toUpperCase())
    for (const mode of modes) {
      expect(primitives[g.themes.default[mode].accent]).toBe(raw[mode].accent.toUpperCase())
      expect(g.themes.default[mode].fg).toBe(raw[mode].fg === 'dark' ? 'graphite-950' : 'white')
    }
  })

  it.each(groupNames)('group %s - contrast theme - uses contrastAccents', (group) => {
    for (const mode of modes) {
      expect(groups[group].themes.contrast[mode].accent).toBe(contrastAccents[group][mode])
    }
  })

  it('ops - every mode - is magenta, never the superseded amber (B-30)', () => {
    expect(primitives[groups.ops.fill]).toBe('#EE4FFF')
    for (const theme of themeNames)
      for (const mode of modes) expect(groups.ops.themes[theme][mode].accent).not.toMatch(/^amber/)
  })

  it('primitiveForHex - unknown value - throws', () => {
    expect(() => primitiveForHex('#123456')).toThrow(/no primitive/)
    expect(primitiveForHex('#ee4fff')).toBe('magenta-400')
  })
})

/** vm-brand `brand.json` `base.dark.page`. B-54: the one dark page on every surface. */
const BRAND_DARK_PAGE = '#0a0a0b'

describe('dark page (vm-brand B-54)', () => {
  it.each(groupNames)('default dark, group %s - --bg - is brand.json base.dark.page', (group) => {
    expect(resolveColors('default', 'dark', group).bg).toBe(BRAND_DARK_PAGE.toUpperCase())
  })

  it('brand.night - primitive - is the dark page', () => {
    expect(primitives[brand.night]).toBe(BRAND_DARK_PAGE.toUpperCase())
    expect(primitiveForHex(BRAND_DARK_PAGE)).toBe(brand.night)
  })

  it('tokens.json - default dark bg and brand.night - are the dark page', () => {
    const json = JSON.parse(renderTokensJson())
    expect(json.themes.default.dark.colors.bg).toBe(BRAND_DARK_PAGE.toUpperCase())
    expect(json.brand.night).toBe(brand.night)
  })
})

describe('group style (B-46)', () => {
  it('venture - style - Cinzel, near-square corners, ornament, tracking', () => {
    const s = groups.venture.style
    expect(s.display).toMatch(/^"Cinzel"/)
    expect(s).toMatchObject({ corner: 0.15, ornament: true, tracking: '0.02em' })
  })

  it.each(['flagship', 'lab', 'ops'] as const)('%s - style - is the plain D-41 style', (group) => {
    expect(groups[group].style).toEqual(plainGroupStyle)
  })

  it('venture rule - css - declares the style properties', () => {
    const d = decls(groupSelector('venture'))
    expect(d.get('--group-font-display')).toMatch(/^"Cinzel"/)
    expect(d.get('--group-corner')).toBe('0.15')
    expect(d.get('--group-ornament')).toBe('1')
    expect(d.get('--group-tracking')).toBe('0.02em')
  })

  it.each(groupNames)('%s rule - css - resets every style property', (group) => {
    const d = decls(groupSelector(group))
    for (const name of ['font-display', 'corner', 'ornament', 'tracking'])
      expect(d.has(`--group-${name}`)).toBe(true)
  })

  it('default rule - css - is the plain style', () => {
    const d = decls(':where(:root, [data-theme], [data-group])')
    expect(d.get('--group-font-display')).toBe('var(--font-display)')
    expect(d.get('--group-corner')).toBe('1')
    expect(d.get('--group-ornament')).toBe('0')
    expect(defaultGroup).toBe('flagship')
  })
})

describe('deprecated aliases (one release)', () => {
  it('aliases - map - vlm to lab, rig to ops', () => {
    expect(deprecatedGroupAliases).toEqual({ vlm: 'lab', rig: 'ops' })
    expect(resolveGroupName('vlm')).toBe('lab')
    expect(resolveGroupName('rig')).toBe('ops')
    expect(resolveGroupName('venture')).toBe('venture')
  })

  it.each(Object.entries(deprecatedGroupAliases))(
    'data-group="%s" - css - shares the rule of %s',
    (alias, group) => {
      const selector = groupSelector(group)
      expect(selector).toContain(`[data-group="${alias}"], `)
      expect(selector).toContain(`[data-group="${alias}"] [data-theme]:not([data-group])`)
    }
  )

  it.each(Object.entries(deprecatedGroupAliases))(
    'resolveColors(%s) - every theme × mode - equals %s',
    (alias, group) => {
      for (const theme of themeNames)
        for (const mode of modes)
          expect(resolveColors(theme, mode, alias as 'vlm' | 'rig')).toEqual(
            resolveColors(theme, mode, group)
          )
    }
  )

  it('tokens.json - groups - lists the four groups and the aliases', () => {
    const json = JSON.parse(renderTokensJson())
    expect(Object.keys(json.groups)).toEqual([...groupNames])
    expect(json.groupAliases).toEqual(deprecatedGroupAliases)
    expect(json.groups.venture.style.corner).toBe(0.15)
  })
})
